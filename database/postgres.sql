CREATE FUNCTION social_media_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := CURRENT_TIMESTAMP;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TABLE account_groups (
  id varchar(36) NOT NULL,
  name varchar(64) NOT NULL,
  description varchar(256),
  platform_code varchar(32),
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX account_groups_idx_platform ON account_groups (platform_code);
CREATE INDEX account_groups_idx_sort ON account_groups (sort_order);
CREATE TRIGGER touch_updated_at BEFORE UPDATE ON account_groups FOR EACH ROW EXECUTE FUNCTION social_media_touch_updated_at();

